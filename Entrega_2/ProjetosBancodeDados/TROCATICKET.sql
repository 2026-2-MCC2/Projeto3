-- Script SQL do banco TROCATICKET
-- Compatível com MySQL 5.7+ / MySQL 8.0.
-- ATENÇÃO: DROP DATABASE apaga o banco TROCATICKET existente e todos os seus dados.

DROP DATABASE IF EXISTS TROCATICKET;
CREATE DATABASE TROCATICKET;
USE TROCATICKET;

CREATE TABLE IF NOT EXISTS USUARIOS (
    ID_USUARIO INT PRIMARY KEY AUTO_INCREMENT,
    NOME VARCHAR(120) NOT NULL,
    EMAIL VARCHAR(50) NOT NULL UNIQUE,
    SENHA VARCHAR(255) NOT NULL,
    PERFIL VARCHAR(50) NOT NULL,
    MFA_SECRET VARCHAR(64) NULL,
    STATUS_CADASTRO VARCHAR(20) NOT NULL DEFAULT 'APROVADO',
    MOTIVO_REPROVACAO TEXT NULL,
    CHECKLIST_JSON JSON NULL,
    APROVADO_EM DATETIME NULL,
    CRIADO_EM TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS ORGANIZADORES (
    ID_ORGANIZADOR INT PRIMARY KEY AUTO_INCREMENT,
    ID_USUARIO INT,
    CNPJ VARCHAR(50) UNIQUE NOT NULL,
    TELEFONE VARCHAR(50) NOT NULL,
    CONSTRAINT FKOrganizador FOREIGN KEY (ID_USUARIO)
        REFERENCES USUARIOS (ID_USUARIO)
);

CREATE TABLE IF NOT EXISTS FORNECEDORES (
    ID_FORNECEDOR INT PRIMARY KEY AUTO_INCREMENT,
    ID_USUARIO INT,
    CNPJ VARCHAR(50) UNIQUE NOT NULL,
    CATEGORIA VARCHAR(50),
    DESCRICAO TEXT,
    CONSTRAINT FKFornecedor FOREIGN KEY (ID_USUARIO)
        REFERENCES USUARIOS (ID_USUARIO)
);

CREATE TABLE IF NOT EXISTS DOCUMENTOS (
    ID_DOCUMENTO INT PRIMARY KEY AUTO_INCREMENT,
    ID_USUARIO INT NOT NULL,
    NOME_ARQUIVO VARCHAR(255) NOT NULL,
    MIME_TYPE VARCHAR(100) NOT NULL,
    CONTEUDO LONGBLOB NOT NULL,
    CRIADO_EM TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT FKDocumentoUsuario FOREIGN KEY (ID_USUARIO)
        REFERENCES USUARIOS (ID_USUARIO)
);

CREATE TABLE IF NOT EXISTS ADMIN_AUDITORIA (
    ID_AUDITORIA INT PRIMARY KEY AUTO_INCREMENT,
    ID_ADMIN INT NOT NULL,
    ENTIDADE VARCHAR(50) NOT NULL,
    ACAO VARCHAR(50) NOT NULL,
    ALVO VARCHAR(255) NOT NULL,
    JUSTIFICATIVA TEXT,
    CRIADO_EM TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT FKAuditoriaAdmin FOREIGN KEY (ID_ADMIN)
        REFERENCES USUARIOS (ID_USUARIO)
);

CREATE TABLE IF NOT EXISTS EVENTOS (
    ID_EVENTO INT PRIMARY KEY AUTO_INCREMENT,
    ID_ORGANIZADOR INT,
    NOME VARCHAR(100) NOT NULL,
    LOCALIZACAO VARCHAR(50) NOT NULL,
    DATA_INICIO DATETIME NOT NULL,
    DATA_FINAL DATETIME NOT NULL,
    PUBLICO_MINIMO INT NOT NULL,
    PUBLICO_MAXIMO INT NOT NULL,
    MARGEM_LUCRO DOUBLE NOT NULL,
    STATUS VARCHAR(50),
    DADOS_JSON JSON NULL,
    CONSTRAINT FKEvento FOREIGN KEY (ID_ORGANIZADOR)
        REFERENCES ORGANIZADORES (ID_ORGANIZADOR)
);

CREATE TABLE IF NOT EXISTS ITENS (
    ID_ITEM INT PRIMARY KEY AUTO_INCREMENT,
    ID_EVENTO INT,
    NOME VARCHAR(50) NOT NULL,
    CATEGORIA VARCHAR(50) NOT NULL,
    QUANTIDADE INT NOT NULL,
    CONSTRAINT FKItem FOREIGN KEY (ID_EVENTO)
        REFERENCES EVENTOS (ID_EVENTO)
);

CREATE TABLE IF NOT EXISTS CUSTOS (
    ID_CUSTO INT PRIMARY KEY AUTO_INCREMENT,
    ID_EVENTO INT,
    DESCRICAO VARCHAR(50),
    CATEGORIA VARCHAR(50) NOT NULL,
    VALOR DOUBLE NOT NULL,
    CONSTRAINT FKCusto FOREIGN KEY (ID_EVENTO)
        REFERENCES EVENTOS (ID_EVENTO)
);

CREATE TABLE IF NOT EXISTS PROPOSTAS (
    ID_PROPOSTA INT PRIMARY KEY AUTO_INCREMENT,
    ID_FORNECEDOR INT,
    VALOR DOUBLE NOT NULL,
    DESCRICAO TEXT,
    VALIDADE DATE NOT NULL,
    SITUACAO VARCHAR(50) NOT NULL,
    CONSTRAINT FKProposta FOREIGN KEY (ID_FORNECEDOR)
        REFERENCES FORNECEDORES (ID_FORNECEDOR)
);

CREATE TABLE IF NOT EXISTS SELECOES (
    ID_SELECAO INT PRIMARY KEY AUTO_INCREMENT,
    ID_PROPOSTA INT,
    DATA_SELECAO DATETIME,
    CONSTRAINT FKSelecao FOREIGN KEY (ID_PROPOSTA)
        REFERENCES PROPOSTAS (ID_PROPOSTA)
);
