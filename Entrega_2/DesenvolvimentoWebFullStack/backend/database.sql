-- Recria o banco do zero (use só em desenvolvimento!)
DROP DATABASE IF EXISTS TROCATICKET;
CREATE DATABASE TROCATICKET;
USE TROCATICKET;

CREATE TABLE IF NOT EXISTS USUARIOS (
ID_USUARIO INT PRIMARY KEY auto_increment,
NOME VARCHAR (50) NOT NULL,
EMAIL VARCHAR (50) NOT NULL UNIQUE,
SENHA VARCHAR (255) NOT NULL, -- era 50: o hash do bcrypt tem 60 caracteres
PERFIL VARCHAR (50) NOT NULL
);

CREATE TABLE IF NOT EXISTS ORGANIZADORES (
ID_ORGANIZADOR INT PRIMARY KEY auto_increment,
ID_USUARIO INT,
CNPJ VARCHAR (50) UNIQUE NOT NULL,
TELEFONE VARCHAR (50) NOT NULL,
CONSTRAINT FKOrganizador FOREIGN KEY (ID_USUARIO) REFERENCES USUARIOS (ID_USUARIO)
);

CREATE TABLE IF NOT EXISTS FORNECEDORES (
ID_FORNECEDOR INT PRIMARY KEY auto_increment,
ID_USUARIO INT,
CNPJ VARCHAR (50) UNIQUE NOT NULL,
CATEGORIA VARCHAR (50),
DESCRICAO TEXT (50),
CONSTRAINT FKFornecedor FOREIGN KEY (ID_USUARIO) REFERENCES USUARIOS (ID_USUARIO)
);

CREATE TABLE IF NOT EXISTS EVENTOS (
ID_EVENTO INT PRIMARY KEY auto_increment,
ID_ORGANIZADOR INT,
NOME VARCHAR (50) NOT NULL,
LOCALIZACAO VARCHAR (50) NOT NULL,
DATA_INICIO DATETIME NOT NULL,
DATA_FINAL DATETIME NOT NULL,
PUBLICO_MINIMO INT NOT NULL,
PUBLICO_MAXIMO INT NOT NULL,
MARGEM_LUCRO DOUBLE NOT NULL,
STATUS VARCHAR (50),
CONSTRAINT FKEvento FOREIGN KEY (ID_ORGANIZADOR) REFERENCES ORGANIZADORES (ID_ORGANIZADOR)
);

CREATE TABLE IF NOT EXISTS ITENS (
ID_ITEM INT PRIMARY KEY auto_increment,
ID_EVENTO INT,
NOME VARCHAR (50) NOT NULL,
CATEGORIA VARCHAR (50) NOT NULL,
QUANTIDADE INT NOT NULL,
CONSTRAINT FKItem FOREIGN KEY (ID_EVENTO) REFERENCES EVENTOS (ID_EVENTO)
);

CREATE TABLE IF NOT EXISTS CUSTOS (
ID_CUSTO INT PRIMARY KEY auto_increment,
ID_EVENTO INT,
DESCRICAO VARCHAR (50),
CATEGORIA VARCHAR (50) NOT NULL,
VALOR DOUBLE NOT NULL,
CONSTRAINT FKCusto FOREIGN KEY (ID_EVENTO) REFERENCES EVENTOS (ID_EVENTO)
);

CREATE TABLE IF NOT EXISTS PROPOSTAS (
ID_PROPOSTA INT PRIMARY KEY auto_increment,
ID_FORNECEDOR INT,
VALOR DOUBLE NOT NULL,
DESCRICAO TEXT,
VALIDADE DATE NOT NULL,
SITUACAO VARCHAR (50) NOT NULL,
CONSTRAINT FKProposta FOREIGN KEY (ID_FORNECEDOR) REFERENCES FORNECEDORES (ID_FORNECEDOR)
);

CREATE TABLE IF NOT EXISTS SELECOES (
ID_SELECAO INT PRIMARY KEY auto_increment,
ID_PROPOSTA INT,
DATA_SELECAO DATETIME,
CONSTRAINT FKSelecao FOREIGN KEY (ID_PROPOSTA) REFERENCES PROPOSTAS (ID_PROPOSTA)
);
